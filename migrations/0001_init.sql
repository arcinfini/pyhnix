CREATE SCHEMA AUDIT;

CREATE TYPE AUDIT.AUDIT_KIND AS ENUM ('AUDIT', 'DISCORD', 'TEAM');

CREATE TABLE AUDIT.DELETABLE (
	IS_DELETED BOOL DEFAULT FALSE
);

CREATE TABLE AUDIT.AUDIT_ACTION (
	ID UUID DEFAULT GEN_RANDOM_UUID(),
	MESSAGE TEXT
	
	PRIMARY KEY (ID)
);

CREATE TABLE AUDIT.AUDIT (
	ID INT GENERATED BY DEFAULT AS IDENTITY,
	AUDIT_ACTION_ID UUID REFERENCES AUDIT.AUDIT_ACTION(ID),
	KIND AUDIT.AUDIT_KIND NOT NULL,
	DATA JSON DEFAULT '{}',
	DATETIME TIMESTAMP DEFAULT NOW()
	
	PRIMARY KEY (ID)
);

CREATE SCHEMA TEAMS;

CREATE TABLE TEAMS.TEAM (
	ID INT GENERATED BY DEFAULT AS IDENTITY,
	GUILD_ID SNOWFLAKE,
	NAME VARCHAR(100),
	
	PRIMARY KEY (GUILD_ID, ID),
	UNIQUE (ID)
) INHERITS (AUDIT.DELETABLE);

CREATE TABLE TEAMS.MEMBER (
	TEAM_ID INT REFERENCES TEAMS.TEAM(ID) ON DELETE CASCADE,
	USER_ID SNOWFLAKE,
	
	PRIMARY KEY (TEAM_ID, USER_ID)
) INHERITS (AUDIT.DELETABLE);
