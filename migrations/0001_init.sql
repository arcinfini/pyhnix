CREATE DOMAIN SNOWFLAKE AS BIGINT;
CREATE DOMAIN SETTING_KEY VARCHAR(100)
CHECK (
	VALUE ~ '^[^A-Z]+$'
	AND VALUE IS NOT NULL
);

/* SETTING
 *
 * Global settings meant to alter behavior of the entire application. 
 * 
 */
CREATE TABLE SETTING (
	name SETTING_KEY PRIMARY KEY,
	value JSON DEFAULT '{}',
	
	last_edited TIMESTAMP DEFAULT NOW()
);

CREATE TABLE GUILD_SETTING (
	name SETTING_KEY,
	guild_id SNOWFLAKE,
	value JSON DEFAULT '{}',

	last_edited TIMESTAMP DEFAULT NOW(),
	
	PRIMARY KEY (name, guild_id)
);

----- FUNCTIONS

/* TS_TO_RELATIVE_DISCORD_MD
 * 
 * Formats a TIMESTAMP into supported discord markdown for displaying relative times to users.
 * 
 * */
CREATE FUNCTION ts_to_relative_discord_md(
	x TIMESTAMP, 
	focus VARCHAR(1) DEFAULT 'T'
) RETURNS TEXT AS $$

	SELECT 
		CONCAT_WS('', '<', focus, ':', extract(epoch FROM x)::INTEGER, '>')

$$ LANGUAGE SQL;

/* UPSERT_SETTING
 * 
 * */
CREATE PROCEDURE UPSERT_SETTING(q_name SETTING_KEY, q_value JSON) AS $$

	INSERT INTO SETTING VALUES (q_name, q_value)
	ON CONFLICT (name) DO UPDATE 
		SET value=q_value,
		last_edited=NOW()

$$ LANGUAGE SQL;

/* UPSERT_GUILD_SETTING
 * 
 * */
CREATE PROCEDURE UPSERT_GUILD_SETTING(q_name SETTING_KEY, guild SNOWFLAKE, q_value JSON) AS $$

	INSERT INTO GUILD_SETTING VALUES (q_name, guild, q_value)
	ON CONFLICT (name) DO UPDATE 
		SET value=q_value,
		last_edited=NOW()

$$ LANGUAGE SQL;

